import catalog from "./games-catalog.json";

export type HubGame = {
  id: string;
  name: string;
  url: string;
  category?: string;
  description?: string;
  tags?: string[];
  editorsPick?: boolean;
  views?: number;
};

export const HUB_ORIGIN = "https://games.mathclass.uk";

/** Play counts are placeholders until the hub publishes real counts. */
const VIEW_COUNTS: Record<string, number> = {
  "game-run3": 3900,
  "game-retro-bowl": 4800,
  "game-cookie-clicker": 2600,
  "game-geometry-dash": 3100,
  "game-happy-wheels": 2200,
};

/**
 * Snapshot of https://games.mathclass.uk/catalog.json, the same catalogue the
 * hub searches. Regenerated by `npm run sync:games` before dev and build.
 */
export const HUB_GAMES: HubGame[] = catalog.map((game) => ({
  ...game,
  views: VIEW_COUNTS[game.id],
}));

export const MOST_VIEWED = HUB_GAMES.filter((game) => game.views).sort(
  (a, b) => (b.views ?? 0) - (a.views ?? 0),
);

export function hubSearchUrl(query: string) {
  const trimmed = query.trim();
  return trimmed ? `${HUB_ORIGIN}/?q=${encodeURIComponent(trimmed)}` : `${HUB_ORIGIN}/`;
}
